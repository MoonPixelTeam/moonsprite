"""Execute unmodified legacy Rust Adobe parsers to build native regression fixtures."""
from pathlib import Path
import hashlib
import math
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "legacy/src-tauri/src/platform_palette.rs"
OWNED = ROOT / "native/build/palette-adobe-oracle-owned"
OUTPUT = ROOT / "native/tests/fixtures/palette_adobe_legacy.h"
OWNED.mkdir(parents=True, exist_ok=True)
source = SOURCE.read_text(encoding="utf-8")
start = source.index("fn read_u16_be(")
end = source.index("fn act_imported_colors(", start)
legacy = source[start:end]
# The driver adds only transport and the legacy color data shape.
driver = r"""
use std::io::Write;
#[derive(Debug)] struct PaletteColor {r:u8,g:u8,b:u8,a:u8}
fn main() {
 let input=std::fs::read(std::env::args().nth(1).unwrap()).unwrap();
 let mut p=0usize;let mut out=Vec::new();
 while p<input.len() {
  let kind=input[p];p+=1;
  let n=u32::from_le_bytes(input[p..p+4].try_into().unwrap()) as usize;p+=4;
  let result=if kind==0 {ase_imported_colors(&input[p..p+n])} else {aco_imported_colors(&input[p..p+n])};p+=n;
  match result {Ok(colors)=>{out.push(1);out.extend_from_slice(&(colors.len() as u32).to_le_bytes());for c in colors {out.extend_from_slice(&[c.r,c.g,c.b,c.a]);}},Err(_)=>out.push(0)}
 }
 std::io::stdout().write_all(&out).unwrap();
}
"""
(OWNED / "oracle.rs").write_text(driver + legacy, encoding="utf-8")
subprocess.run(["rustc", "--edition=2021", "-O", str(OWNED / "oracle.rs"), "-o", str(OWNED / "oracle.exe")], check=True)
cases=[]
def add(kind, data):
    cases.append((kind, data))
def be16(n): return struct.pack(">H", n)
def be32(n): return struct.pack(">I", n)
def block(model, values, name=b"\0\0"):
    return be16(len(name)//2)+name+model+b"".join(struct.pack(">f",v) for v in values)+be16(0)
def ase(blocks, major=1, minor=0):
    return b"ASEF"+be16(major)+be16(minor)+be32(len(blocks))+b"".join(be16(t)+be32(len(b))+b for t,b in blocks)
def aco(entries, version=1, name=b"\0\0"):
    return be16(version)+be16(len(entries))+b"".join(be16(s)+b"".join(be16(v) for v in values)+(be32(len(name)//2)+name if version==2 else b"") for s,values in entries)
values=[-math.inf,-2,-0.0,0.0,1/510,0.5,0.999,1.0,2,math.inf,math.nan]
for value in values:
    for model,channels in [(b"GRAY",[value]),(b"RGB ",[value,.5,1]),(b"CMYK",[value,.5,1,0]),(b"CMYK",[0,.5,1,value])]:
        add(0,ase([(1,block(model,channels))]))
# Every byte threshold around 8-bit half steps, keeping exact f32 transport.
for i in range(256):
    value=(i+.5)/255
    add(0,ase([(1,block(b"RGB ",[value,1-value,.5]))]))
seed=0x12345678
def rand():
    global seed
    seed=(seed*1664525+1013904223)&0xffffffff
    return seed
for i in range(96):
    channels=[(rand()%4001-1000)/2000 for _ in range(4)]
    add(0,ase([(0xc001,b"group"),(1,block(b"RGB ",channels[:3],b"\xd8\x3d\xde\x80\0\0")),(1,block(b"CMYK",channels)),(1,block(b"LAB ",[])),(0xc002,b"")],65535,i))
for hue in [0,1,10922,10923,21845,32767,32768,43690,54612,54613,65534,65535]:
    for saturation in [0,32768,65535]:
        for value in [0,32768,65535]:
            add(1,aco([(1,[hue,saturation,value,0])]))
for i in range(96):
    entries=[(space,[rand()&65535 for _ in range(4)]) for space in [0,1,8,7,65535]]
    add(1,aco(entries,1+(i%2),b"\xd8\x3d\xde\x80\0\0"))
representativeAse=ase([(0xc001,b""),(1,block(b"RGB ",[.1,.5,.9])),(1,block(b"GRAY",[.25])),(0xc002,b"")])
representativeAco=aco([(0,[0x1100,0x2200,0x3300,0]),(1,[65535,65535,65535,0])],2)
for kind,data in [(0,representativeAse),(1,representativeAco)]:
    for n in range(len(data)):
        add(kind,data[:n])
    add(kind,data)
add(0,ase([(1,block(b"UNKNOWN"[:4],[]))]))
add(0,b"ASEF"+be16(1)+be16(0)+be32(1000001))
add(0,b"ASEF"+be16(1)+be16(0)+be32(1)+be16(1)+be32(0xffffffff))
add(1,aco([],3))
add(1,aco([(0,[0,0,0,0])])+representativeAco)
add(1,be16(2)+be16(1)+be16(0)+b"\0"*8+be32(0xffffffff))
for kind in [0,1]:
    add(kind,ase([]) if kind==0 else aco([]))
inputBytes=b"".join(bytes([kind])+struct.pack("<I",len(data))+data for kind,data in cases)
(OWNED / "input.bin").write_bytes(inputBytes)
result=subprocess.run([str(OWNED / "oracle.exe"),str(OWNED / "input.bin")],check=True,capture_output=True).stdout
p=0
rows=[]
for kind,data in cases:
    accepted=result[p];p+=1
    colors=[]
    if accepted:
        count=struct.unpack_from("<I",result,p)[0];p+=4
        for _ in range(count):
            colors.append(struct.unpack_from("<I",result,p)[0]);p+=4
    rows.append("{"+str(kind)+",{"+",".join(str(v) for v in data)+"},"+("true" if accepted else "false")+",{"+",".join(hex(c)+"u" for c in colors)+"}}")
assert p==len(result)
header="#pragma once\n// Generated by make-palette-adobe-fixtures.py from actual legacy Rust parsers.\n// Source SHA256: "+hashlib.sha256(SOURCE.read_bytes()).hexdigest()+"\n"
header+="struct LegacyAdobeFixture {int kind;std::vector<std::uint8_t> bytes;bool accepted;std::vector<moon::Pixel> colors;};\ninline const std::vector<LegacyAdobeFixture> legacyAdobeFixtures={\n"+",\n".join(rows)+"\n};\n"
OUTPUT.write_text(header,encoding="utf-8",newline="\n")
print(f"Generated {len(cases)} actual legacy Rust ASE/ACO cases")
