const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { stripTypeScriptTypes } = require('node:module');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'legacy/src/renderer/src/core/isometric.ts'), 'utf8');
const context = vm.createContext({});
vm.runInContext(stripTypeScriptTypes(source.replace(/^import type .*$/gm, '').replace(/^export /gm, ''), { mode: 'transform' }) + `
globalThis.api = { snapIsoPointToGridVertex, isoGuideSpacingForZoom, isoGuidePixelPattern,
isoGuideSegments, isoLineEndpoint, isoGridLineSegment, isoGridLineEndpoint,
traceIsoGridPointerEdges, advanceIsoAlignedStrokeSegment, updateIsoAlignedStrokePath };`, context);
const api = context.api;
const num = n => Number.isNaN(n) ? 'NAN' : n === Infinity ? 'INFINITY' : n === -Infinity ? '-INFINITY' : Object.is(n, -0) ? '-0.0' : String(n);
const point = p => `Point{${num(p.x)},${num(p.y)}}`;
const vector = (a, encode, type) => `std::vector<${type}>{${a.map(encode).join(',')}}`;
const optional = (v, encode) => v == null ? 'std::nullopt' : encode(v);
const directions = ['right', 'down', 'left', 'up', 'down-right', 'down-left', 'up-left', 'up-right'];
const direction = d => d == null ? 'std::nullopt' : `Direction(${directions.indexOf(d)})`;
const stateFields = s => [point(s.anchor), point(s.endpoint), optional(s.rawAnchor, point), optional(s.rawEndpoint, point), optional(s.gridVertex, point), direction(s.direction), optional(s.directionSamples, num)].join(',');
const state = s => `StrokeState{${stateFields(s)}}`;
const advance = s => `StrokeAdvance{{${stateFields(s)}},${optional(s.initialAnchor, point)},${optional(s.lockedEndpoint, point)},${optional(s.lockedEndpoints, a => vector(a, point, 'Point'))}}`;
const grid = g => `GridOptions{${num(g.spacing)},${point(g.origin ?? { x: 0, y: 0 })}}`;
const options = o => `StrokeOptions{${!!o.diagonalOnly},${optional(o.grid, grid)}}`;
const edge = e => `GridEdge{${JSON.stringify(e.key)},${[e.from,e.to,e.startVertex,e.endVertex].map(point).join(',')}}`;
const traceOptions = o => `TraceOptions{${grid(o)},${num(o.stairStep ?? 2)},${num(o.hitRadius ?? .55)},${num(o.sampleStep ?? .25)},${optional(o.hoveredEdgeKey, JSON.stringify)}}`;
const traceResult = r => `TraceResult{${vector(r.edges, edge, 'GridEdge')},${optional(r.hoveredEdgeKey, JSON.stringify)}}`;
const sample = s => `Sample{${num(s.x)},${num(s.y)},${num(s.pressure)},${s.id}}`;
const lines = ['// Generated by make-isometric-fixtures.cjs from the actual legacy implementation.', 'inline void legacyFixtures() {'];
let checks = 0;
const check = (call, expected) => lines.push(`check(${call},${expected},"legacy case ${++checks}");`);
let seed = 0x1502026;
const random = n => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed % n; };
const randomPoint = () => ({ x: (random(321) - 160) / 2, y: (random(241) - 120) / 2 });
const steps = [1, 2, 3, 4, 16, 0, -2, 1.5, 2.5, 17, NaN, Infinity];
const spacings = [1, 2, 5, 8, 16, 7.5, 0, -2, NaN, Infinity];
for (let i = 0; i < 192; ++i) {
  const a = randomPoint(), b = i % 13 === 0 ? a : randomPoint(), step = steps[i % steps.length], spacing = spacings[i % spacings.length], origin = randomPoint();
  check(`isoLineEndpoint(${point(a)},${point(b)},${num(step)})`, point(api.isoLineEndpoint(a, b, step)));
  const segment = api.isoGridLineSegment(a, b, step);
  check(`isoGridLineSegment(${point(a)},${point(b)},${num(step)})`, `LineSegment{${point(segment.from)},${point(segment.to)}}`);
  check(`isoGridLineEndpoint(${point(a)},${point(b)},${num(step)})`, point(segment.to));
  check(`snapIsoPointToGridVertex(${point(a)},${num(step)},${num(spacing)},${point(origin)})`, point(api.snapIsoPointToGridVertex(a, step, spacing, origin)));
}
for (const step of steps) for (const spacing of spacings) {
  const p = api.isoGuidePixelPattern(step, spacing);
  check(`isoGuidePixelPattern(${num(step)},${num(spacing)})`, `PixelPattern{${num(p.width)},${num(p.height)},${vector(p.pixels, point, 'Point')}}`);
}
for (const zoom of [0, -.5, .0001, .25, .5, 1, 2, 8, NaN, Infinity]) for (const spacing of spacings)
  check(`isoGuideSpacingForZoom(${num(zoom)},${num(spacing)})`, num(api.isoGuideSpacingForZoom(zoom, spacing)));
for (let i = 0; i < 72; ++i) {
  const width = i % 13 === 0 ? NaN : 32, height = i % 17 === 0 ? -1 : 24;
  const bounds = i % 7 === 0 ? { left: 50, top: 40, right: 60, bottom: 50 } : { left: -5 + random(18), top: -3 + random(10), right: 16 + random(30), bottom: 12 + random(20) };
  const o = { stairStep: steps[i % steps.length], spacing: spacings[i % spacings.length], origin: i % 3 ? randomPoint() : { x: NaN, y: Infinity } };
  check(`isoGuideSegments(${num(width)},${num(height)},Bounds{${Object.values(bounds).map(num).join(',')}},GuideOptions{${num(o.spacing)},${num(o.stairStep)},${point(o.origin)}})`, vector(api.isoGuideSegments(width, height, bounds, o), s => `Segment{${point(s.start)},${point(s.end)}}`, 'Segment'));
}
// Pointer entry, exit, re-entry, tie at a vertex, preferred key, invalid radii.
const traces = [
  [{ x: 3, y: 0 }, { x: 3, y: 3 }, { stairStep: 2, spacing: 8 }],
  [{ x: 0, y: 0 }, { x: 0, y: 0 }, { spacing: 8 }],
  [{ x: 0, y: 0 }, { x: 0, y: 0 }, { spacing: 8, hoveredEdgeKey: '0:0:1' }],
  [{ x: 0, y: 0 }, { x: 4, y: 2 }, { spacing: 8, hoveredEdgeKey: '0:0:1' }],
];
for (let i = 0; i < 60; ++i) traces.push([randomPoint(), randomPoint(), { spacing: spacings[i % 10], stairStep: steps[i % 12], origin: randomPoint(), hitRadius: [0, .55, 2, NaN][i % 4], sampleStep: [.25, 1, NaN][i % 3] }]);
for (const [a, b, o] of traces) check(`traceIsoGridPointerEdges(${point(a)},${point(b)},${traceOptions(o)})`, traceResult(api.traceIsoGridPointerEdges(a, b, o)));
const sequences = [
  [{ x: 0, y: 0 }, [{ x: 1, y: 0 }, { x: 1, y: 1 }, { x: 3, y: 2 }], 2, {}],
  [{ x: 0, y: 0 }, [{ x: 6, y: 3 }, { x: 11, y: -1 }, { x: 16, y: 0 }, { x: -16, y: -8 }], 2, { grid: { spacing: 8 } }],
];
for (let i = 0; i < 48; ++i) sequences.push([randomPoint(), Array.from({ length: 9 }, randomPoint), steps[i % 12], { diagonalOnly: !!(i % 2), ...(i % 3 === 0 ? { grid: { spacing: spacings[i % 10], origin: randomPoint() } } : {}) }]);
for (const [start, targets, step, o] of sequences) {
  let s = { anchor: start, endpoint: start, direction: null };
  let samples = [{ ...start, pressure: .25, id: 0 }];
  for (let i = 0; i < targets.length; ++i) {
    const target = targets[i], advanced = api.advanceIsoAlignedStrokeSegment(s, target, step, o);
    check(`advanceIsoAlignedStrokeSegment(${state(s)},${point(target)},${num(step)},${options(o)})`, advance(advanced));
    const before = samples.map(p => ({ ...p })), next = { ...advanced.endpoint, pressure: (i + 1) / 10, id: i + 1 };
    api.updateIsoAlignedStrokePath(samples, advanced, next);
    lines.push(`checkPath(${vector(before, sample, 'Sample')},${advance(advanced)},${sample(next)},${vector(samples, sample, 'Sample')},"legacy path ${++checks}");`);
    s = advanced;
  }
}
// Explicit old tests for established turns and complete active grid edges.
for (const o of [{}, { diagonalOnly: true, grid: { spacing: 8 } }]) {
  const s = { anchor: { x: 0, y: 0 }, endpoint: o.grid ? { x: 6, y: 3 } : { x: 11, y: 5 }, rawAnchor: { x: 0, y: 0 }, rawEndpoint: o.grid ? { x: 6, y: 3 } : { x: 14, y: 1 }, direction: 'down-right', directionSamples: o.grid ? 4 : 8 }, t = o.grid ? { x: 11, y: -1 } : { x: 15, y: 0 };
  check(`advanceIsoAlignedStrokeSegment(${state(s)},${point(t)},2,${options(o)})`, advance(api.advanceIsoAlignedStrokeSegment(s, t, 2, o)));
}
// Path branch coverage: empty path, repeated endpoint, empty locked list takes precedence.
for (const count of [0, 1, 2, 3, 4]) for (const locked of [undefined, [], [{ x: 8, y: 4 }, { x: 16, y: 0 }]]) {
  const before = Array.from({ length: count }, (_, id) => ({ x: 1, y: 2, pressure: id / 4, id }));
  const a = { anchor: { x: 3, y: 4 }, endpoint: { x: 9, y: 6 }, direction: null, lockedEndpoint: { x: 8, y: 4 }, lockedEndpoints: locked, initialAnchor: { x: -1, y: 1 } }, t = { x: 9, y: 6, pressure: .75, id: 99 }, after = before.map(s => ({ ...s }));
  api.updateIsoAlignedStrokePath(after, a, t);
  lines.push(`checkPath(${vector(before, sample, 'Sample')},${advance(a)},${sample(t)},${vector(after, sample, 'Sample')},"legacy path ${++checks}");`);
}
const statements = lines.slice(2), chunks = [];
for (let i = 0; i < statements.length; i += 40) chunks.push(statements.slice(i, i + 40));
const output = [lines[0], ...chunks.map((chunk, i) => `inline void legacyFixtures${i}() {\n${chunk.join('\n')}\n}`),
  `inline void legacyFixtures() {${chunks.map((_, i) => `legacyFixtures${i}();`).join('')}}`,
  `inline constexpr int legacyFixtureCount = ${checks};`, ''];
fs.writeFileSync(path.join(root, 'native/tests/fixtures/isometric_legacy.h'), output.join('\n'));
console.log(`Generated ${checks} legacy ISO checks`);
